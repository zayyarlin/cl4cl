(ns cl4cl.dev.checklist
  "Render doc/spec-checklist.md from the spec and spec/implemented.edn."
  (:require [cl4cl.dev.spec :as spec]
            [clojure.edn :as edn]
            [clojure.string :as str]))

(def implemented-file "spec/implemented.edn")
(def checklist-file "doc/spec-checklist.md")

(def kinds
  "Checklist sections in order: [kind title what-implemented-means]."
  [[:api-version "API version"
    "The default `anthropic-version` header is this version."]
   [:endpoint "Endpoints"
    "A public function calls the endpoint."]
   [:request-header "Request headers"
    "The client can send the header."]
   [:request-param "Create a Message: body parameters"
    "A value of the parameter's type reaches the wire unchanged."]
   [:count-tokens-param "Count tokens: body parameters"
    "A value of the parameter's type reaches the wire unchanged."]
   [:request-block "Request content blocks"
    "A block of this type reaches the wire unchanged."]
   [:tool "Tool definitions"
    "A tool of this type reaches the wire unchanged."]
   [:response-field "Response: Message fields"
    "The field is returned unchanged, and assembled correctly from a stream."]
   [:response-block "Response content blocks"
    "The block is returned unchanged, and assembled correctly from a stream."]
   [:stop-reason "Stop reasons"
