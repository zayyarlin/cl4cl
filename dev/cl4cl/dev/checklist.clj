(defn load-implemented
  ([] (load-implemented implemented-file))
  ([file] (set (edn/read-string (slurp file)))))

(defn- line [implemented {:keys [id title type optional? status] :as item}]
  (str "- [" (if (implemented (spec/item-key item)) "x" " ") "] `" id "`"
       (when title (str " (" title ")"))
       (when type (str ": " (when optional? "optional ") type))
       (when status (str " (HTTP " status ")"))))

(defn render
  "The checklist markdown for the given items and set of implemented keys."
  [items implemented]
  (let [by-kind (group-by :kind items)
        done (count (filter (comp implemented spec/item-key) items))]
    (str/join
     "\n"
     (concat
      ["# Messages API spec checklist"
       ""
       "Generated by `bb spec:checklist` from `spec/upstream/` and `spec/implemented.edn`. Do not edit by hand."
       ""
       (str "Implemented: " done " of " (count items) ".")
       ""]
      (mapcat (fn [[kind title meaning]]
                (concat [(str "## " title) "" (str "Implemented means: " meaning) ""]
                        (map (partial line implemented) (by-kind kind))
                        [""]))
              kinds)))))

(defn current
  "The checklist as it should be for the files on disk."
  []
  (render (spec/items (spec/load-spec)) (load-implemented)))

(defn write! []
  (spit checklist-file (current)))
